const saveCourseOutlineToDBService = async (
  outline,
  userId,
  intent,
  embedding,
  prompt,
) => {
  if (!outline?.course || !outline?.modules) {
    throw new Error("Invalid course outline structure");
  }

  const session = await mongoose.startSession();

  try {
    session.startTransaction();

    const { course, modules } = outline;

    //-------------------------------------
    // Create Course
    //-------------------------------------

    const [template] = await CourseTemplate.create([
      {
        title: course.title || "Untitled Course",
        description: course.description || "Course generated by AI",
        learningIntent: intent,
        outline,
        embedding,
      },
    ], { session });

    const [createdCourse] = await Course.create(
      [
        {
          title: course.title || "Untitled Course",

          description: course.description || "Course generated by AI",

          userId,

          learningIntent: {
            topic: intent.topic,
            goal: intent.goal,
            level: intent.level,
            targetRole: intent.targetRole,

            canonicalQuery: intent.canonicalQuery,

            confidence: intent.confidence,
          },

          embedding,

          generatedFromPrompt: prompt,
          templateId: template._id,
        },
      ],
      { session },
    );

    //-------------------------------------
    // Create Modules + Lessons
    //-------------------------------------

    for (const moduleData of modules) {
      const [createdModule] = await Module.create(
        [
          {
            moduleIndex: moduleData.moduleIndex,

            title: moduleData.title,

            description: moduleData.description,
            course: createdCourse._id,
          },
        ],
        { session },
      );

      //-------------------------------------
      // Build Lessons
      //-------------------------------------

      const lessonDocuments = moduleData.lessons.map((lesson) => ({
        lessonIndex: lesson.lessonIndex,

        title: lesson.title,

        realWorldProblem: lesson.realWorldProblem,

        learnerTakeaway: lesson.learnerTakeaway,

        completionCriteria: lesson.completionCriteria,

        briefDescription: lesson.briefDescription,

        estimatedMinutes: lesson.estimatedMinutes || 30,
        skillTags: lesson.skillTags || [],
        handsOnTask: lesson.handsOnTask,
        resources: lesson.resources || [],

        module: createdModule._id,

        content: null,

        isGenerated: "PENDING",
      }));

      let createdLessons = [];
      if (lessonDocuments.length > 0) {
        createdLessons = await Lesson.insertMany(lessonDocuments, { session });
      }

      // Add lesson IDs to module.lessons
      createdModule.lessons = createdLessons.map(l => l._id);
      await createdModule.save({ session });

      // Add module ID to course.modules
      createdCourse.modules.push(createdModule._id);
    }

    // Save course with modules
    await createdCourse.save({ session });
    await Enrollment.create([{ userId, templateId: template._id, courseId: createdCourse._id }], { session });

    await session.commitTransaction();

    // Fetch the full course with populated modules/lessons to return
    const fullCourse = await Course.findById(createdCourse._id)
      .populate({
        path: "modules",
        populate: { path: "lessons" },
      })
      .session(session)
      .lean();

    return fullCourse;
  } catch (error) {
    await session.abortTransaction();

    throw error;
  } finally {
    session.endSession();
  }
};

