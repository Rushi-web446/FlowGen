const saveCourseOutlineToDBService = async (
  outline,
  userId,
  intent,
  embedding,
  prompt,
) => {
  if (!outline?.course || !outline?.modules) {
    throw new Error("Invalid course outline structure");
  }

  const session = await mongoose.startSession();

  try {
    session.startTransaction();

    const { course, modules } = outline;

    //-------------------------------------
    // Create Course
    //-------------------------------------

    const [createdCourse] = await Course.create(
      [
        {
          title: course.title || "Untitled Course",

          description: course.description || "Course generated by AI",

          userId,

          learningIntent: {
            topic: intent.topic,
            goal: intent.goal,
            level: intent.level,
            targetRole: intent.targetRole,

            canonicalQuery: intent.canonicalQuery,

            confidence: intent.confidence,
          },

          embedding,

          generatedFromPrompt: prompt,
        },
      ],
      { session },
    );

    //-------------------------------------
    // Create Modules + Lessons
    //-------------------------------------

    for (const moduleData of modules) {
      const [createdModule] = await Module.create(
        [
          {
            moduleIndex: moduleData.moduleIndex,

            title: moduleData.title,

            description: moduleData.description,

            course: createdCourse._id,
          },
        ],
        { session },
      );

      //-------------------------------------
      // Build Lessons
      //-------------------------------------

      const lessonDocuments = moduleData.lessons.map((lesson) => ({
        lessonIndex: lesson.lessonIndex,

        title: lesson.title,

        realWorldProblem: lesson.realWorldProblem,

        learnerTakeaway: lesson.learnerTakeaway,

        completionCriteria: lesson.completionCriteria,

        briefDescription: lesson.briefDescription,

        module: createdModule._id,

        content: null,

        isGenerated: "PENDING",
      }));

      if (lessonDocuments.length > 0) {
        await Lesson.insertMany(lessonDocuments, { session });
      }
    }

    await session.commitTransaction();

    return createdCourse;
  } catch (error) {
    await session.abortTransaction();

    throw error;
  } finally {
    session.endSession();
  }

  return createdCourse;
};

