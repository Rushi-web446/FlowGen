// Send course via SSE
const sendCourse = (res, course) => {
  try {
    if (!course) {
      res.write(
        `data: ${JSON.stringify({
          type: "ERROR",
          message: "Course data not found",
        })}\n\n`,
      );
      return res.end();
    }

    res.write(
      `data: ${JSON.stringify({
        type: "SUCCESS",
        message: "Course generated successfully",
        course: {
          _id: course._id,
          title: course.title,
          description: course.description,
          learningIntent: course.learningIntent,
        },
      })}\n\n`,
    );

    return res.end();
  } catch (error) {
    console.error("sendCourse error:", error);
    res.write(
      `data: ${JSON.stringify({
        type: "ERROR",
        message: "Error sending course data",
      })}\n\n`,
    );
    return res.end();
  }
};



const generateCourseFlow = async (prompt, res, userId) => {
  try {
    if (!prompt || !userId) {
      stream(res, "Error: Missing prompt or userId");
      return res.end();
    }

    stream(res, "🎯 Extracting learning intent from your prompt...");

    const intent = await intentGenerationService({ prompt });

    if (!intent || !intent.canonicalQuery) {
      throw new Error("Failed to extract learning intent");
    }

    stream(res, "🔍 Generating semantic embedding...");

    const embedding = await generateEmbedding(intent.canonicalQuery);

    stream(res, "🔎 Searching for similar existing courses...");

    const similar = await searchVectorDB(embedding, intent);

    if (similar && similar.score > 0.85 && similar._id) {
      console.log(
        `✅ Found existing course with ${(similar.score * 100).toFixed(1)}% similarity`,
      );

      stream(
        res,
        `✨ Found a similar course (${(similar.score * 100).toFixed(1)}% match)! Returning existing course...`,
      );

      // Get the full course with modules/lessons populated
      return sendCourse(res, similar);
    }

    console.log(
      `❌ No similar course found (best match: ${similar ? (similar.score * 100).toFixed(1) : 0}%)`,
    );

    stream(
      res,
      "🚀 No similar course found. Generating brand new course structure...",
    );

    const course = await generateOutlineService(intent);

    if (!course) {
      throw new Error("Failed to create new course");
    }

    stream(res, "✅ Course generated successfully!");

    const savedCourse = saveCourseOutlineToDBService(
      course,
      userId,
      intent,
      embedding,
      prompt,
    );

    stream(res, "✅ Course saved successfully!");

    // await addLessonToLazyLessonGenerationQueue(savedCourse._id);

    return sendCourse(res, savedCourse);

  } catch (error) {
    console.error("❌ generateCourseFlow error:", error);

    res.write(
      `data: ${JSON.stringify({
        type: "ERROR",
        message: error.message || "Course generation failed",
        error: process.env.NODE_ENV === "development" ? error.stack : undefined,
      })}\n\n`,
    );

    return res.end();
  }
};

const getCourseDetailsWithProgressService = async (courseId, userId) => {
  if (!courseId || !userId) {
    throw new Error("Course ID and User ID are required");
  }

  const course = await findById(courseId); // now populates modules + lessons
  if (!course) {
    throw new Error("Course not found");
  }

  // Find first incomplete module
  let currentModuleIndex = 1;
  let currentLessonIndex = 1;

  let found = false;
  for (const mod of course.modules) {
    for (const lesson of mod.lessons) {
      if (!lesson.isCompleted) {
        currentModuleIndex = mod.moduleIndex;
        currentLessonIndex = lesson.lessonIndex;
        found = true;
        break;
      }
    }
    if (found) break;
  }

  // All lessons completed — point to the last lesson
  if (!found && course.modules.length > 0) {
    const lastMod = course.modules[course.modules.length - 1];
    currentModuleIndex = lastMod.moduleIndex;
    const lastLesson = lastMod.lessons[lastMod.lessons.length - 1];
    currentLessonIndex = lastLesson ? lastLesson.lessonIndex : 1;
  }

  return {
    course,
    progress: {
      currentModule: currentModuleIndex,
      currentLesson: currentLessonIndex,
    },
  };
};

