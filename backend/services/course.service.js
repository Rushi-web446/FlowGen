const saveLessonService = async (moduleId, lessonId, lesson, userId) => {
  let actualLesson = lesson;

  if (!moduleId || !lessonId || !actualLesson) {
    throw new Error("Missing required parameters for saving lesson");
  }

  if (userId) {
    const ownedLesson = await findLessonForUser({ moduleId, lessonId, userId });
    if (!ownedLesson) throw new Error("Lesson not found");
  }

  let lessonPayload = {};

  if (actualLesson && actualLesson.data) {
    lessonPayload.content = actualLesson.data;
  } else if (actualLesson && actualLesson.content) {
    lessonPayload = actualLesson;
  } else {
    lessonPayload.content = actualLesson;
  }

  const savedLesson = await saveLesson(moduleId, lessonId, lessonPayload);

  if (!savedLesson) {
    throw new Error("Failed to save lesson (Course/Module/Lesson not found)");
  }

  return savedLesson;
};

